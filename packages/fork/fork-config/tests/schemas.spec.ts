import { readFileSync, writeFileSync } from 'node:fs'
import { runInNewContext } from 'node:vm'
import { describe, expect, it } from 'vitest'
import { Config as QqConfig } from '@deepseek-ai/dsh-fork-qq'
import { buildFields } from '../src/fields.ts'
import { leavesOf } from '../src/view.ts'

/** Every Config field of `fork-qq`, as dotted paths; a new field in its schema must appear here and in the card. */
const QQ_FIELDS = [
  'url', 'tokenEnv', 'groups', 'dataDir',
  'media.images', 'media.maxImageBytes', 'media.maxTotalBytes', 'media.retainDays', 'media.hostSuffixes', 'media.timeoutMs',
  'voice.download', 'voice.maxBytes', 'asr.enabled', 'retention.textDays', 'honorRecall',
  'backfill.enabled', 'backfill.maxMessages', 'backfill.maxGroups', 'backfill.gapMs', 'backfill.skipWithinMs', 'backfill.minIntervalMs',
  'send.enabled', 'send.groups', 'send.minIntervalSec', 'send.maxPerDay',
  'digest.enabled', 'digest.everyHours', 'digest.minMessages', 'digest.maxPromptChars', 'digest.maxCallsPerRound',
  'digest.aliasMembers', 'digest.profiles', 'digest.keepPerGroup', 'digest.maxDigestChars', 'digest.provider', 'digest.model',
  'digest.agentPreset', 'digest.permissionPreset', 'digest.workspacePath', 'digest.timeZone', 'digest.timeoutMs',
  'offlineNoticeMs', 'reconnectQuietMs', 'offlineRepeatMs', 'settingsUrl',
  'login.enabled', 'login.url', 'login.timeoutMs',
]

describe('the fork-qq schema as a form', () => {
  const fields = buildFields(QqConfig, { effective: {}, inherited: {}, locked: false })
  const leaves = leavesOf(fields)

  it('has a leaf for every Config field and a group for every nested object', () => {
    expect(leaves.map(leaf => leaf.path.join('.')).sort()).toEqual([...QQ_FIELDS].sort())
    expect(fields.filter(node => node.kind === 'group').map(node => node.key)).toEqual(['media', 'voice', 'asr', 'retention', 'backfill', 'send', 'digest', 'login'])
  })

  it('edits each field by its type, and shows the credential reference by name only', () => {
    const kind = (path: string) => leaves.find(leaf => leaf.path.join('.') === path)!
    expect(kind('tokenEnv')).toMatchObject({ kind: 'credential-ref', default: 'FORK_QQ_ONEBOT_TOKEN' })
    expect(kind('groups')).toMatchObject({ kind: 'string-list', default: [] })
    expect(kind('honorRecall')).toMatchObject({ kind: 'boolean', default: true })
    expect(kind('media.maxImageBytes')).toMatchObject({ kind: 'number', min: 1024, step: 1 })
    expect(kind('digest.provider')).toMatchObject({ kind: 'string', required: false })
    expect(leaves.every(leaf => leaf.readOnly === undefined)).toBe(true)
  })

  it('marks the fields that apply without a reload, and only those', () => {
    const volatile = leaves.filter(leaf => leaf.volatile === true).map(leaf => leaf.path.join('.'))
    expect(volatile).toEqual(expect.arrayContaining(['groups', 'media.images', 'backfill.gapMs', 'offlineNoticeMs', 'reconnectQuietMs', 'settingsUrl']))
    for (const connection of ['url', 'tokenEnv', 'dataDir', 'login.url', 'digest.enabled', 'send.enabled']) {
      expect(volatile).not.toContain(connection)
    }
  })
})

/** The client tests render this file; it is read as text because the client and Host programs do not share test files. */
const FIXTURE = new URL('./qq-form.client.ts', import.meta.url)

describe('the fork-qq form fixture', () => {
  it('is the form the fork-qq schema builds, so the card test renders the real field set', () => {
    const built = JSON.parse(JSON.stringify(buildFields(QqConfig, { effective: {}, inherited: {}, locked: false }))) as unknown
    if (process.env['UPDATE_QQ_FORM'] === '1') {
      const header = '/** Generated by UPDATE_QQ_FORM=1 on schemas.spec.ts, then lint --fix: the form the fork-qq schema builds. */'
      writeFileSync(
        FIXTURE,
        `${header}\nimport type { FieldNode } from '../src/view.ts'\n\nexport const QQ_FORM: FieldNode[] = ${JSON.stringify(built, null, 2)}\n`,
      )
    }
    const text = readFileSync(FIXTURE, 'utf8')
    const literal = text.slice(text.indexOf('= [') + 2)
    expect(runInNewContext(`(${literal})`)).toEqual(built)
  })
})
